def enc(rows):
    out = []
    for r in range(0, len(rows), 8):
        for y in range(8):
            lo = hi = 0
            for ch in rows[r + y]:
                c = int(ch); lo = (lo << 1) | (c & 1); hi = (hi << 1) | (c >> 1)
            out += [lo, hi]
    return out

def fmt(name, data, cm):
    s = 'static const uint8_t %s[%d] = {  // %s\n' % (name, len(data), cm)
    for i in range(0, len(data), 16):
        s += '  ' + ','.join('0x%02X' % v for v in data[i:i + 16]) + ',\n'
    return s + '};\n'

