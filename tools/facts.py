OK = set("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 :!/.-+?<>_")
def wrap(t, w=26):
    out, cur = [], ""
    for word in t.split(" "):
        if len(word) > w: raise SystemExit("word too long: " + word)
        if not cur: cur = word
        elif len(cur) + 1 + len(word) <= w: cur += " " + word
        else: out.append(cur); cur = word
    if cur: out.append(cur)
    return out
